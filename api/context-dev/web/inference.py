"""Context.dev Web: one function per upstream operation.

Generated once by belt from https://docs.context.dev/openapi.json and then yours: belt never rewrites this
file. `_generated.py` (models, operations) is regenerated by
`belt app init --openapi context-dev/openapi.plan.yaml`; a spec change surfaces here as a type
error. Rename parameters, add defaults, reshape responses and report usage
in output_meta here (see pricing.md).
"""

import logging

from inferencesh import BaseApp, OutputMeta, RawMeta, function
from inferencesh.upstream import UpstreamClient

from . import _generated as g


# Pricing reads what a call produced, never the vendor's own charge: inputs
# are priced as sent, and a function whose cost depends on its result reports
# the count here (see pricing.md). upstream_credits is what context.dev says it
# charged: informational, to check the price against, never priced on.
def usage(data, **produced: int) -> OutputMeta:
    metadata = data.get("key_metadata") if isinstance(data, dict) else None
    reported = metadata.get("credits_consumed") if isinstance(metadata, dict) else None
    extra = {**produced, "upstream_credits": reported} if reported is not None else produced
    logging.getLogger(__name__).info("context.dev usage %s", extra)
    return OutputMeta(inputs=[], outputs=[RawMeta(extra=extra)] if extra else [])


def count(data, key: str) -> int:
    items = data.get(key) if isinstance(data, dict) else None
    return len(items) if isinstance(items, list) else 0


class App(BaseApp):
    async def setup(self, config):
        self.logger = logging.getLogger(__name__)
        self.client = UpstreamClient(g.BASE_URL, auth=g.AUTH, default_auth=g.DEFAULT_AUTH, logger=self.logger)

    @function(annotations=g.scrape.annotations, credentials=g.scrape.credentials)
    async def scrape(self, input_data: g.ScrapeInput) -> g.ScrapeOutput:
        """Scrape Anything"""
        data = await self.client.call(g.scrape, input_data)
        return g.ScrapeOutput.from_response(data, output_meta=usage(data))

    @function(annotations=g.crawl.annotations, credentials=g.crawl.credentials)
    async def crawl(self, input_data: g.CrawlInput) -> g.CrawlOutput:
        """Crawl a website"""
        data = await self.client.call(g.crawl, input_data)
        return g.CrawlOutput.from_response(data, output_meta=usage(data, pages=count(data, "results")))

    @function(annotations=g.search.annotations, credentials=g.search.credentials)
    async def search(self, input_data: g.SearchInput) -> g.SearchOutput:
        """Search the web"""
        data = await self.client.call(g.search, input_data)
        return g.SearchOutput.from_response(data, output_meta=usage(data, results=count(data, "results")))

    @function(annotations=g.map_urls.annotations, credentials=g.map_urls.credentials)
    async def map_urls(self, input_data: g.MapUrlsInput) -> g.MapUrlsOutput:
        """Map URLs"""
        data = await self.client.call(g.map_urls, input_data)
        return g.MapUrlsOutput.from_response(data, output_meta=usage(data))

    @function(annotations=g.extract.annotations, credentials=g.extract.credentials)
    async def extract(self, input_data: g.ExtractInput) -> g.ExtractOutput:
        """Extract structured data"""
        data = await self.client.call(g.extract, input_data)
        return g.ExtractOutput.from_response(data, output_meta=usage(data))

    @function(annotations=g.answer.annotations, credentials=g.answer.credentials)
    async def answer(self, input_data: g.AnswerInput) -> g.AnswerOutput:
        """Answer a research task"""
        data = await self.client.call(g.answer, input_data)
        return g.AnswerOutput.from_response(data, output_meta=usage(data))

    async def unload(self):
        await self.client.aclose()
