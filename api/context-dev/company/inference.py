import logging

from inferencesh import BaseApp, OutputMeta, function
from inferencesh.upstream import UpstreamClient

from . import _generated as g

# Free to run as written: every function reports an empty OutputMeta. Metered
# functions report what they consumed instead (see pricing.md).
FREE = OutputMeta(inputs=[], outputs=[])


class App(BaseApp):
    async def setup(self, config):
        self.logger = logging.getLogger(__name__)
        self.client = UpstreamClient(g.BASE_URL, auth=g.AUTH, default_auth=g.DEFAULT_AUTH, logger=self.logger)

    @function(annotations=g.company_search.annotations, credentials=g.company_search.credentials)
    async def company_search(self, input_data: g.CompanySearchInput) -> g.CompanySearchOutput:
        """Search companies"""
        data = await self.client.call(g.company_search, input_data)
        return g.CompanySearchOutput.from_response(data, output_meta=FREE)

    async def unload(self):
        await self.client.aclose()
