"""Exa: one function per upstream operation.

Generated once by belt from https://api.exa.ai/openapi.json and then yours: belt never rewrites this
file. `_generated.py` (models, operations) is regenerated by
`belt app init --openapi exa/openapi.plan.yaml`; a spec change surfaces here as a type
error. Rename parameters, add defaults, reshape responses and report usage
in output_meta here (see pricing.md).
"""

import logging

from inferencesh import BaseApp, OutputMeta, function
from inferencesh.upstream import UpstreamClient

from . import _generated as g

# Free to run as written: every function reports an empty OutputMeta. Metered
# functions report what they consumed instead (see pricing.md).
FREE = OutputMeta(inputs=[], outputs=[])


class App(BaseApp):
    async def setup(self, config):
        self.logger = logging.getLogger(__name__)
        self.client = UpstreamClient(g.BASE_URL, auth=g.AUTH, default_auth=g.DEFAULT_AUTH, logger=self.logger)

    @function(annotations=g.answer.annotations, credentials=g.answer.credentials)
    async def answer(self, input_data: g.AnswerInput) -> g.AnswerOutput:
        """Answer"""
        data = await self.client.call(g.answer, input_data)
        return g.AnswerOutput.from_response(data, output_meta=FREE)

    @function(annotations=g.get_contents.annotations, credentials=g.get_contents.credentials)
    async def get_contents(self, input_data: g.GetContentsInput) -> g.GetContentsOutput:
        """Contents"""
        data = await self.client.call(g.get_contents, input_data)
        return g.GetContentsOutput.from_response(data, output_meta=FREE)

    @function(annotations=g.find_similar.annotations, credentials=g.find_similar.credentials)
    async def find_similar(self, input_data: g.FindSimilarInput) -> g.FindSimilarOutput:
        """Find similar links"""
        data = await self.client.call(g.find_similar, input_data)
        return g.FindSimilarOutput.from_response(data, output_meta=FREE)

    @function(annotations=g.search.annotations, credentials=g.search.credentials)
    async def search(self, input_data: g.SearchInput) -> g.SearchOutput:
        """Search"""
        data = await self.client.call(g.search, input_data)
        return g.SearchOutput.from_response(data, output_meta=FREE)

    async def unload(self):
        await self.client.aclose()
